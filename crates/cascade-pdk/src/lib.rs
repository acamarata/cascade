//! cascade-pdk — Plugin Development Kit for Cascade WASM plugins.
//!
//! # Purpose
//! Provides the guest-side counterpart to the host's WIT bindings in
//! `cascade-plugins`. Plugin authors add this crate as a dependency,
//! implement the [`Plugin`] trait on their struct, apply the
//! [`macro@cascade_plugin`] attribute, and compile with
//! `--target wasm32-wasip1`.
//!
//! # JSON-string ABI
//! The Cascade host communicates with WASM guests via a JSON-string ABI:
//! - Every call is serialised to a JSON UTF-8 string.
//! - The guest receives a pointer + length pair referencing host-owned memory.
//! - The guest returns a pointer + length pair to guest-owned memory.
//! - Memory is managed via the exported `alloc` / `dealloc` pair below.
//!
//! # Architecture
//! ```text
//! Host (cascade-plugins) --- JSON bytes ---> guest WASM
//!   call_export_json()                        cascade_plugin_call()
//!                      <--- JSON bytes ---
//! ```
//!
//! # Target notes
//! `wasm32-wasip1` is a full WASI target — std is available.
//! `no_std` is NOT used; std is the correct choice here.
//!
//! # Usage example
//! ```rust,ignore
//! use cascade_pdk::{cascade_plugin, Plugin, PluginKind, ToolCall, ToolResult, PluginError};
//!
//! #[cascade_plugin]
//! pub struct MyTool;
//!
//! impl Plugin for MyTool {
//!     fn name(&self) -> &str { "my-tool" }
//!     fn kind(&self) -> PluginKind { PluginKind::ChatTool }
//!
//!     fn on_tool_call(&self, call: ToolCall) -> Result<ToolResult, PluginError> {
//!         Ok(ToolResult {
//!             call_id: call.call_id,
//!             output: format!("Hello from my-tool: {}", call.args_json),
//!             data_json: None,
//!         })
//!     }
//! }
//! ```
//!
//! Inputs:  cascade-plugins host WIT ABI (JSON-string encoding)
//! Outputs: serde-serialised return values through the ABI
//! Constraints: no std::fs, std::net, or std::thread in this crate
//! SPORT: cascade-pdk crate (T-P4-E03-10)

