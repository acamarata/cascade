// ── WASM memory management exports ───────────────────────────────────────────
// The host uses these to allocate/free memory when passing JSON strings in.
// Only compiled for wasm32 targets — on host they are unused.

/// Allocate `len` bytes and return the pointer.
///
/// The host calls this before writing a JSON argument string into guest memory.
/// On wasm32-wasip1 std is available so we use the standard allocator directly.
#[cfg(target_arch = "wasm32")]
#[no_mangle]
pub extern "C" fn alloc(len: usize) -> *mut u8 {
    let layout = std::alloc::Layout::array::<u8>(len).expect("layout");
    // Safety: layout is valid (non-zero size, aligned for u8).
    unsafe { std::alloc::alloc(layout) }
}

/// Free a slice of memory previously allocated by [`alloc`].
///
/// Called by the host after it has read the guest's return value.
#[cfg(target_arch = "wasm32")]
#[no_mangle]
pub extern "C" fn dealloc(ptr: *mut u8, len: usize) {
    if len == 0 {
        return;
    }
    let layout = std::alloc::Layout::array::<u8>(len).expect("layout");
    // Safety: ptr was returned by alloc() with the same len.
    unsafe { std::alloc::dealloc(ptr, layout) }
}

