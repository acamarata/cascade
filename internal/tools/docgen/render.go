// Package docgen renders a cobra command tree and the config-key reference
// to markdown pages, writes a generator-owned tree atomically and diffs a
// tree against disk (contract:docs-generator).
package docgen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/spf13/cobra"
)

// OwnedMarker is the first line of every generated page. A file carrying it
// is generator-owned; a file without it is never overwritten or deleted.
const OwnedMarker = "<!-- generated by docgen; do not edit -->"

// Page is one generated markdown file; Path is slash-separated and relative
// to the tree root.
type Page struct {
	Path string
	Body []byte
}

// ConfigKey is one row of the config-key reference.
type ConfigKey struct {
	Key     string
	Type    string
	Default string
	Doc     string
}

// RenderCommands renders one page per visible command in the tree under
// root, named by the command path with spaces turned into underscores.
// Output order and bytes are deterministic.
func RenderCommands(root *cobra.Command) []Page {
	var pages []Page
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		name := strings.ReplaceAll(c.CommandPath(), " ", "_") + ".md"
		pages = append(pages, Page{Path: name, Body: []byte(renderCommand(c))})
		subs := append([]*cobra.Command(nil), c.Commands()...)
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
		for _, s := range subs {
			if s.Hidden || !s.IsAvailableCommand() {
				continue
			}
			walk(s)
		}
	}
	walk(root)
	return pages
}

func renderCommand(c *cobra.Command) string {
	var b strings.Builder
	b.WriteString(OwnedMarker + "\n\n")
	fmt.Fprintf(&b, "# %s\n\n", c.CommandPath())
	if c.Short != "" {
		b.WriteString(c.Short + "\n\n")
	}
	if c.Long != "" {
		b.WriteString(c.Long + "\n\n")
	}
	if c.Runnable() {
		fmt.Fprintf(&b, "```\n%s\n```\n\n", c.UseLine())
	}
	if u := c.NonInheritedFlags().FlagUsages(); u != "" {
		fmt.Fprintf(&b, "## Flags\n\n```\n%s```\n\n", u)
	}
	writeSubcommands(&b, c)
	return b.String()
}

func writeSubcommands(b *strings.Builder, c *cobra.Command) {
	subs := append([]*cobra.Command(nil), c.Commands()...)
	sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
	wrote := false
	for _, s := range subs {
		if s.Hidden || !s.IsAvailableCommand() {
			continue
		}
		if !wrote {
			b.WriteString("## Subcommands\n\n")
			wrote = true
		}
		file := strings.ReplaceAll(s.CommandPath(), " ", "_") + ".md"
		fmt.Fprintf(b, "- [%s](%s): %s\n", s.CommandPath(), file, s.Short)
	}
	if wrote {
		b.WriteString("\n")
	}
}

// RenderConfigKeys renders the config-key reference as one table page at
// path, with rows sorted by key.
func RenderConfigKeys(path string, keys []ConfigKey) Page {
	sorted := append([]ConfigKey(nil), keys...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Key < sorted[j].Key })
	var b strings.Builder
	b.WriteString(OwnedMarker + "\n\n# Config keys\n\n")
	b.WriteString("| Key | Type | Default | Description |\n|---|---|---|---|\n")
	for _, k := range sorted {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", cell(k.Key), cell(k.Type), cell(k.Default), cell(k.Doc))
	}
	return Page{Path: path, Body: []byte(b.String())}
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}
