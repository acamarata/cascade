package toolchain

import (
	"errors"
	"testing"
)

func TestEmptyFileFails(t *testing.T) {
	called := false
	regen := func() ([]byte, error) {
		called = true
		return nil, nil
	}

	if err := CheckGenerated(nil, regen); !errors.Is(err, ErrM1469) {
		t.Fatalf("nil content: got %v, want ErrM1469", err)
	}
	if called {
		t.Fatal("nil content: regen must not be invoked")
	}

	called = false
	if err := CheckGenerated([]byte{}, regen); !errors.Is(err, ErrM1469) {
		t.Fatalf("empty content: got %v, want ErrM1469", err)
	}
	if called {
		t.Fatal("empty content: regen must not be invoked")
	}
}

func TestMissingHeaderFails(t *testing.T) {
	called := false
	regen := func() ([]byte, error) {
		called = true
		return nil, nil
	}

	tests := []struct {
		name    string
		content []byte
	}{
		{"no header", []byte("package main\n")},
		{"BOM prefix", append([]byte{0xEF, 0xBB, 0xBF}, []byte(GeneratedHeader)...)},
		{"leading space", append([]byte(" "), []byte(GeneratedHeader)...)},
		{"CRLF instead of LF", []byte("// Code generated by capp. DO NOT EDIT.\r\n")},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			called = false
			err := CheckGenerated(tc.content, regen)
			if !errors.Is(err, ErrM1469) {
				t.Fatalf("got %v, want ErrM1469", err)
			}
			if called {
				t.Fatal("regen must not be invoked on header mismatch")
			}
		})
	}
}
