package tmplguard

import (
	"strings"
	"testing"
)

func TestRenderPlainText(t *testing.T) {
	tmpl := "Hello {{.Name}}"
	data := map[string]string{"Name": "Ada"}
	out, err := Render("greeting", tmpl, data)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if out != "Hello Ada" {
		t.Fatalf("expected 'Hello Ada', got %q", out)
	}
}

func TestRenderRejectsModelStruct(t *testing.T) {
	tmpl := "type UserModel struct {}"
	_, err := Render("model", tmpl, nil)
	if err == nil {
		t.Fatal("expected ErrModelGeneration, got nil")
	}
	if !strings.Contains(err.Error(), "model generation") {
		t.Fatalf("expected model generation error, got: %v", err)
	}
}

func TestRenderRejectsModelGeneratedHeader(t *testing.T) {
	tmpl := "// Code generated by model gen"
	_, err := Render("genheader", tmpl, nil)
	if err == nil {
		t.Fatal("expected ErrModelGeneration, got nil")
	}
	if !strings.Contains(err.Error(), "model generation") {
		t.Fatalf("expected model generation error, got: %v", err)
	}
}

func TestRenderParseErrorWrapped(t *testing.T) {
	tmpl := "{{.Name"
	_, err := Render("bad", tmpl, nil)
	if err == nil {
		t.Fatal("expected parse error, got nil")
	}
}
