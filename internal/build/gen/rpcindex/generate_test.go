package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func testRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs("../../../..")
	if err != nil {
		t.Fatal(err)
	}
	return root
}

func TestRPCMethodReference_MatchesCommitted(t *testing.T) {
	root := testRoot(t)
	ok, err := matchesCommitted(root)
	if err != nil {
		t.Fatal(err)
	}
	if !ok {
		t.Fatal("docs/reference/rpc-methods.md differs from regeneration; run go run ./internal/build/gen/rpcindex")
	}
	page, err := os.ReadFile(filepath.Join(root, pagePath))
	if err != nil {
		t.Fatal(err)
	}
	if rows := strings.Count(string(page), "\n| `"); rows < 40 {
		t.Fatalf("page has %d method rows, want >= 40", rows)
	}
	golden, err := os.ReadFile(filepath.Join(root, "cmd/cascade/testdata/daemon_rpc_methods.golden"))
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range strings.Split(string(golden), "\n") {
		m := strings.TrimSpace(line)
		if m != "" && !strings.HasPrefix(m, "#") && !strings.Contains(string(page), "| `"+m+"` |") {
			t.Errorf("golden method %q has no row", m)
		}
	}
}

func TestGenerateRefusesBrokenTree(t *testing.T) {
	root := t.TempDir()
	dest := filepath.Join(root, "out.md")
	if err := generate(root, dest); err == nil {
		t.Fatal("generate on a tree without the method golden must fail")
	}
	if _, err := os.Stat(dest); err == nil {
		t.Fatal("a failed generate must write nothing")
	}
	if _, err := matchesCommitted(root); err == nil {
		t.Fatal("matchesCommitted on a broken tree must fail")
	}
}

func TestFindRootFromSubdir(t *testing.T) {
	root := testRoot(t)
	t.Chdir(filepath.Join(root, "internal", "build"))
	got, err := findRoot()
	if err != nil {
		t.Fatal(err)
	}
	if got != root {
		t.Fatalf("findRoot = %q, want %q", got, root)
	}
}

func TestGenerateWritesCommittedBytes(t *testing.T) {
	dest := filepath.Join(t.TempDir(), "page.md")
	if err := generate(testRoot(t), dest); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(dest)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile(filepath.Join(testRoot(t), pagePath))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(want) {
		t.Fatal("generated bytes differ from the committed page")
	}
}

func TestRunFailsOutsideRepo(t *testing.T) {
	t.Chdir(t.TempDir())
	var buf bytes.Buffer
	if code := run(&buf); code != 1 || !strings.Contains(buf.String(), "rpcindex:") {
		t.Fatalf("run = %d %q, want 1 with a message", code, buf.String())
	}
}

func TestRenderReportsFindings(t *testing.T) {
	root := t.TempDir()
	golden := filepath.Join(root, "cmd/cascade/testdata/daemon_rpc_methods.golden")
	if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(golden, []byte("no.such_method\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := render(root); err == nil {
		t.Log("render accepted a method with no declaration")
		t.Fatal("render must report findings for an undeclared, undocumented method")
	}
}
